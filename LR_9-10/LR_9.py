# Глобальные переменные
arr = []  # глобальная переменная - массив
n = 0  # глобальная переменная - размер массива


def multiply_all(a: list) -> int:
    """a - ФОРМАЛЬНЫЙ ПАРАМЕТР (передача по ссылке, но мы работаем с копией)"""
    p = 1  # локальная переменная
    for i in range(len(a)):  # i - локальная переменная цикла
        p *= a[i]
    return p


def multiply_even(a: list) -> int:
    """a - ФОРМАЛЬНЫЙ ПАРАМЕТР (передача по ссылке, но мы работаем с копией)"""
    p = 1  # локальная переменная
    for i in range(len(a)):  # i - локальная переменная цикла
        if a[i] % 2 == 0:
            p *= a[i]
    return p


def main():
    global n, arr  # объявляем работу с глобальными переменными

    n = int(input('Введите количество элементов массива: '))  # работа с глобальной переменной n

    print('Введите элементы массива:')
    for i in range(n):  # i - локальная переменная (в Python обычно так)
        arr.append(int(input(f'arr[{i + 1}] = ')))  # работа с глобальной переменной arr

    # multiply_all(arr) - arr ФАКТИЧЕСКИЙ ПАРАМЕТР (передача по ссылке, но функция получает ссылку на список)
    print('Произведение всех элементов: ', multiply_all(arr.copy()))  # используем copy() для передачи копии

    # multiply_even(arr) - arr ФАКТИЧЕСКИЙ ПАРАМЕТР
    print('Произведение четных элементов: ', multiply_even(arr.copy()))  # используем copy() для передачи копии

if __name__ == "__main__":
    main()